//! Writes the generated dylib crate's `Cargo.toml` and `src/lib.rs`.
//!
//! # Invariant
//!
//! The generated crate depends on the sibling checkout's `lichen-language` by
//! path, so the dylib and the toolchain that loads it are built from the same
//! lichen source by the same rustc; the manifest's program and build tags are what
//! say so at load time, and writing the dependency is what makes them true.

use std::path::{Path, PathBuf};

use lichen_language::link::build_tag;
// Inside its own crate the library is named by its package, not by the
// `lichen-stages` key other crates reach it through.
use whiting_lichen_stages::library;

/// The directory the generator writes into.
const CRATE: &str = "lichen-link";

/// The package name inside it; a Whiting crate publishes under the prefix.
const PACKAGE: &str = "whiting-lichen-link";

fn main() {
    let workspace = workspace_root();
    let crate_dir = workspace.join("crates").join(CRATE);
    let program = std::any::type_name::<lichen_language::program::LangProgram>();
    let tag = build_tag();
    let generated = library::source().render::<lichen_language::program::LangProgram>(&tag);
    write(&crate_dir.join("src").join("lib.rs"), &generated);
    write(&crate_dir.join("Cargo.toml"), &manifest(program));
    println!("wrote {PACKAGE}/src/lib.rs ({} bytes)", generated.len());
    println!("program: {program}");
    println!("build:   {tag}");
}

/// The directory this crate's manifest sits two levels under.
fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(2)
        .expect("a member is at least two directories below its workspace root")
        .to_path_buf()
}

/// The generated crate's manifest, with its four dependencies inherited.
///
/// # Invariant
///
/// `lichen-language` is inherited from this workspace's `[workspace.dependencies]`,
/// which is the one arrow that points out to lichen; nothing here names a
/// lichen-vm path directly, so the sibling layout is stated once.
fn manifest(program: &str) -> String {
    format!(
        "# Generated by `cargo run -p whiting-lichen-stages --example generate_link`.\n\
         #\n\
         # `crate-type = [\"dylib\"]` and `lichen-language` by path are the ruling\n\
         # docs/notes/native-link-library.md §4 records: the library is loaded, never\n\
         # linked, and it shares the host's lichen so an entry may cross lichen values.\n\
         [package]\n\
         name = \"{PACKAGE}\"\n\
         version.workspace = true\n\
         edition.workspace = true\n\
         rust-version.workspace = true\n\
         license.workspace = true\n\
         description = \"The alpine-oak stages, loaded through a `link` directive.\"\n\
         \n\
         [lib]\n\
         crate-type = [\"dylib\"]\n\
         path = \"src/lib.rs\"\n\
         \n\
         [dependencies]\n\
         lichen-language = {{ workspace = true }}\n\
         lichen-lowlevel = {{ workspace = true }}\n\
         lichen-utils = {{ workspace = true }}\n\
         lichen-stages = {{ workspace = true }}\n\
         \n\
         # The gate the loader enforces, written where the crate is built.\n\
         # program = {program:?}\n"
    )
}

/// Write `text` to `path`, creating the directory it is in.
fn write(path: &Path, text: &str) {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).expect("the generated crate's directories are writable");
    }
    std::fs::write(path, text).expect("the generated crate's files are writable");
}
