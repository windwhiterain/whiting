/// One culm of the grove, decided by its own hashes.
struct Stalk {
    /// Where it stands.
    x: f64,
    z: f64,
    /// The ground under it.
    ground: f64,
    /// Its height, radius at the base, and how far its tip leans.
    height: f64,
    radius: f64,
    lean: [f64; 2],
    /// The per-stalk hash the shader varies tint by, carried in `texture.x`.
    variety: f64,
    /// How many nodes the culm's shader bands it into.
    nodes: usize,
}

/// Where the grove grows.
///
/// Bamboo stands in groves, not in a sprinkle: a candidate is accepted where a low
/// frequency noise is thick, inside three zones — the grove behind and above the house,
/// and the flanks outside the yard's two side walls — plus three clumps across the
/// valley that the long lens finds in the mist. Everything is a hash of the
/// candidate's index, so the grove is the same grove on every compile.
fn grove_stalks() -> Vec<Stalk> {
    let mut stalks = Vec::new();
    let mut index = 0i64;
    let wanted = 850;
    while stalks.len() < wanted && index < 40000 {
        let x = (hash01(index, 3, 701) - 0.5) * 2.0 * 120.0;
        let z = (hash01(index, 7, 703) - 0.5) * 2.0 * 120.0 - 10.0;
        index += 1;

        // The three zones, and the keep-outs. The yard and the house stand in a
        // courtyard, and a courtyard is swept — nothing grows inside its rectangle.
        let north = z < -13.0 && z > -80.0 && x.abs() < 70.0;
        let west = x < -10.5 && x > -44.0 && z >= -13.0 && z < 18.0;
        let east = x > 10.5 && x < 44.0 && z >= -13.0 && z < 16.0;
        if !(north || west || east) {
            continue;
        }
        let yard = ((x - COURT[0]).powi(2) + (z - COURT[1]).powi(2)).sqrt();
        if yard < 17.0 {
            continue;
        }
        // Clumps, not scatter.
        if fractal_noise([x * 0.045, z * 0.045], 3, 211) < 0.40 {
            continue;
        }
        let ground = terrain_height(x, z);
        if ground > 95.0 || terrain_slope(x, z) > 1.1 {
            continue;
        }

        let variety = hash01(index, 13, 709);
        let height = 6.5 + 5.5 * hash01(index, 17, 711);
        // The grove's edge leans over the yard: a stalk near the keep-out leans towards
        // it, which is where the overhang above the walls comes from.
        let towards_yard = [COURT[0] - x, COURT[1] - z];
        let inward = smoothstep(26.0, 17.5, yard);
        let lean_turn = hash01(index, 19, 713) * TAU;
        let lean_free = 0.06 + 0.16 * hash01(index, 23, 717);
        let lean = [
            lean_turn.cos() * lean_free * (1.0 - inward) + towards_yard[0] * 0.030 * inward,
            lean_turn.sin() * lean_free * (1.0 - inward) + towards_yard[1] * 0.030 * inward,
        ];
        stalks.push(Stalk {
            x,
            z,
            ground,
            height,
            radius: 0.042 + 0.036 * hash01(index, 29, 719),
            lean,
            variety,
            nodes: 8 + (hash01(index, 31, 721) * 4.0) as usize,
        });
    }

    // The three clumps across the valley, looser and taller, for the long lens.
    let clumps: [[f64; 2]; 3] = [[58.0, 64.0], [-46.0, 92.0], [86.0, 34.0]];
    for (clump, centre) in clumps.iter().enumerate() {
        for member in 0..26i64 {
            let index = 40000 + clump as i64 * 100 + member;
            let turn = hash01(index, 3, 731) * TAU;
            let radius = hash01(index, 7, 733).sqrt() * 13.0;
            let (x, z) = (
                centre[0] + turn.cos() * radius,
                centre[1] + turn.sin() * radius * 0.8,
            );
            let ground = terrain_height(x, z);
            let variety = hash01(index, 13, 739);
            stalks.push(Stalk {
                x,
                z,
                ground,
                height: 7.5 + 5.0 * hash01(index, 17, 741),
                radius: 0.036 + 0.028 * hash01(index, 29, 743),
                lean: [
                    (hash01(index, 19, 745) - 0.5) * 0.30,
                    (hash01(index, 23, 747) - 0.5) * 0.30,
                ],
                variety,
                nodes: 9,
            });
        }
    }
    stalks
}

/// The layout a shaded mesh's points are packed with, the same one `geometry` uses.
fn shaded_layout() -> PackedLayout {
    PackedLayout::new([
        ("normal".to_owned(), 3),
        ("position".to_owned(), 3),
        ("texture".to_owned(), 2),
    ])
}

/// Builds the grove's culms as one mesh: a curved, tapering, node-ringed tube apiece.
///
/// # Invariants
///
/// - The centre line is a quadratic in the culm's own parameter: straight at the
///   ground, leaning the most at the tip, which is how a culm leans.
/// - The node is a **ring on the geometry**, a bulge of nine percent, and the shader
///   bands the same nodes by the `texture.y` the ring already carries — so a culm reads
///   as jointed in silhouette and in shading at once.
/// - A culm is six sided. At the distance a grove is read from, a six sided tube is a
///   stalk and a sixteen sided one is a slower stalk.
fn culm_points(stalks: &[Stalk]) -> PackedList {
    const SIDES: usize = 6;
    const BANDS: usize = 16;
    let mut points = PackedBuilder::new(shaded_layout());
    points.reserve(stalks.len() * BANDS * SIDES * 6);

    for stalk in stalks {
        let nodes = stalk.nodes.max(2);
        // The position and radius of the ring at parameter `t`, and the variety and the
        // height fraction the point carries as its texture.
        let ring = |t: f64| -> ([f64; 3], f64) {
            let centre = [
                stalk.x + stalk.lean[0] * t * t,
                stalk.ground - 0.06 + stalk.height * t,
                stalk.z + stalk.lean[1] * t * t,
            ];
            // The node bulge: a narrow pulse at each node's own `t`.
            let phase = t * nodes as f64;
            let bulge = (phase.fract() - 0.5).abs();
            let at_node = smoothstep(0.5, 0.42, bulge) * smoothstep(0.30, 0.42, bulge);
            let radius = stalk.radius * (1.0 - 0.42 * t) * (1.0 + 0.09 * at_node);
            (centre, radius)
        };
        for band in 0..BANDS {
            let t0 = band as f64 / BANDS as f64;
            let t1 = (band + 1) as f64 / BANDS as f64;
            let (c0, r0) = ring(t0);
            let (c1, r1) = ring(t1);
            for side in 0..SIDES {
                let a0 = side as f64 / SIDES as f64 * TAU;
                let a1 = (side + 1) as f64 / SIDES as f64 * TAU;
                // The normal is radial and horizontal: a culm is thin enough that the
                // lean's tilt of its rings is not a thing a fragment can see.
                let point = |centre: [f64; 3], radius: f64, angle: f64, t: f64| {
                    (
                        [
                            centre[0] + angle.cos() * radius,
                            centre[1],
                            centre[2] + angle.sin() * radius,
                        ],
                        [angle.cos(), 0.0, angle.sin()],
                        [stalk.variety, t],
                    )
                };
                let p00 = point(c0, r0, a0, t0);
                let p01 = point(c0, r0, a1, t0);
                let p10 = point(c1, r1, a0, t1);
                let p11 = point(c1, r1, a1, t1);
                for corner in [p00, p10, p01, p10, p11, p01] {
                    push_shaded(&mut points, corner);
                }
            }
        }
    }
    points.finish().expect("the grove's culms pack whole")
}

/// Builds the grove's leaves as one mesh: blades fanned off the top nodes.
///
/// # Invariants
///
/// - A blade is three quads along a drooping spine, flat, because the rasterizer culls
///   nothing and the fold of the blade is painted by the shader's normal rather than by
///   a second surface. Its tip is its own point, so the blade ends in a point rather
///   than a fringe.
/// - Leaves belong to the top of the culm, four nodes of them, fanned around the side
///   the culm leans towards, plus a tuft at the tip. A bamboo's leaf is on its crown,
///   and a culm leafed to the ground reads as a corn stalk.
/// - The blade's texture carries the stalk's variety in `x` and the length along the
///   blade in `y`, which is what the shader dries the tip with.
fn leaf_points(stalks: &[Stalk]) -> PackedList {
    let mut points = PackedBuilder::new(shaded_layout());
    points.reserve(stalks.len() * 20 * 18);

    for (number, stalk) in stalks.iter().enumerate() {
        let base = number as i64;
        let lean_turn = stalk.lean[1].atan2(stalk.lean[0]);
        // The crown: five node heights up the top of the culm, two clusters a node —
        // one on the lean's side and one opposite — so the foliage closes into a
        // canopy rather than a fringe.
        for node in 0..5i64 {
            let t = 0.50 + 0.095 * node as f64 + hash01(base, node, 751) * 0.03;
            let crown = [
                stalk.x + stalk.lean[0] * t * t,
                stalk.ground + stalk.height * t,
                stalk.z + stalk.lean[1] * t * t,
            ];
            for cluster in 0..2i64 {
                let out = 0.10 + 0.14 * hash01(base, node * 2 + cluster, 752);
                let cluster_turn = lean_turn + cluster as f64 * 2.6
                    + (hash01(base, node * 2 + cluster, 754) - 0.5) * 1.2;
                let at = [
                    crown[0] + cluster_turn.cos() * out,
                    crown[1],
                    crown[2] + cluster_turn.sin() * out,
                ];
                let leaves = 8 + (hash01(base, node * 2 + cluster, 753) * 4.0) as i64;
                for leaf in 0..leaves {
                    let seed = base * 80 + node * 20 + cluster * 10 + leaf;
                    let turn = cluster_turn
                        + (hash01(seed, 1, 757) - 0.5) * 2.2
                        + leaf as f64 * (TAU / leaves as f64) * 0.6;
                    let droop = 0.30 + 0.60 * hash01(seed, 3, 761);
                    let length = 0.55 + 0.45 * hash01(seed, 5, 763);
                    push_leaf(&mut points, at, turn, droop, length, stalk.variety);
                }
            }
        }
        // The tip's tuft, smaller and more upright.
        for leaf in 0..8i64 {
            let seed = base * 40 + 400 + leaf;
            let turn = leaf as f64 * (TAU / 8.0) + hash01(seed, 1, 769);
            let droop = 0.12 + 0.40 * hash01(seed, 3, 773);
            let length = 0.34 + 0.26 * hash01(seed, 5, 775);
            push_leaf(
                &mut points,
                [
                    stalk.x + stalk.lean[0],
                    stalk.ground + stalk.height,
                    stalk.z + stalk.lean[1],
                ],
                turn,
                droop,
                length,
                stalk.variety,
            );
        }
    }
    points.finish().expect("the grove's leaves pack whole")
}

/// Appends one blade: three quads along a drooping spine.
///
/// The spine starts at the crown point and runs out at `turn`, dipping by `droop` over
/// its length; the width swells and narrows along it. Both side points share the
/// spine's height, and the shader's normal pretends a fold the geometry does not have.
fn push_leaf(
    points: &mut PackedBuilder,
    origin: [f64; 3],
    turn: f64,
    droop: f64,
    length: f64,
    variety: f64,
) {
    let forward = [turn.cos(), turn.sin()];
    let side = [-forward[1], 0.0, forward[0]];
    // The spine at four stations, and the half width at each.
    let stations = [0.0, 0.38, 0.72, 1.0];
    let half_widths = [0.028, 0.068, 0.048, 0.004];
    let at = |index: usize| -> ([f64; 3], [f64; 3], f64) {
        let t = stations[index];
        let spine = [
            origin[0] + forward[0] * length * t,
            origin[1] - droop * length * t * t,
            origin[2] + forward[1] * length * t,
        ];
        // The blade's normal tilts down the droop and rocks a little across it, so a
        // cluster of leaves does not share one lighting plane.
        let tangent = normalized([forward[0], -2.0 * droop * t, forward[1]]);
        let normal = normalized(cross(tangent, side));
        (spine, normal, half_widths[index])
    };
    for segment in 0..3 {
        let (s0, n0, w0) = at(segment);
        let (s1, n1, w1) = at(segment + 1);
        let t0 = stations[segment];
        let t1 = stations[segment + 1];
        let left0 = subtract(s0, scale(side, w0));
        let right0 = add(s0, scale(side, w0));
        let left1 = subtract(s1, scale(side, w1));
        let right1 = add(s1, scale(side, w1));
        // Up-facing normals, whichever way the blade turned: the fragment stage flips
        // the ones that still face away, because a leaf is lit through as much as on.
        let up0 = if n0[1] < 0.0 { scale(n0, -1.0) } else { n0 };
        let up1 = if n1[1] < 0.0 { scale(n1, -1.0) } else { n1 };
        for (position, normal, t) in [
            (left0, up0, t0),
            (right0, up0, t0),
            (left1, up1, t1),
            (right0, up0, t0),
            (right1, up1, t1),
            (left1, up1, t1),
        ] {
            push_shaded(points, (position, normal, [variety, t]));
        }
    }
}

/// Appends one shaded point to a run.
fn push_shaded(points: &mut PackedBuilder, point: ([f64; 3], [f64; 3], [f64; 2])) {
    points
        .field("normal", &point.1)
        .and_then(|points| points.field("position", &point.0))
        .and_then(|points| points.field("texture", &point.2))
        .expect("the grove writes whole points of its own layout");
}

