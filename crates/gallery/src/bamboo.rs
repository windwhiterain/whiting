/// What the post stage does to the frame.
///
/// The sky and the ranges are drawn where no geometry reached, the mist lies over
/// everything the same way, and the grade is a filmic curve, a touch of warmth in the
/// highlights, and grain last because it belongs to the film rather than the scene.
const GRADE: &str = r#"
    let ray = ray_through(in.uv);
    if depth >= 1.0 {
        var sky = sky_colour(ray);
        sky = ridges(sky, ray);
        color = sky;
    }

    // The weather, on whatever the pixel shows. The world position is recovered from
    // the depth the prepass wrote; for a sky pixel nothing was drawn and the recovery
    // runs to the 2400 unit clamp, which would fog the sky itself past recognition —
    // a sky pixel only carries the air to the top of the mist, not to the far plane.
    let world = world_position(in.uv, depth);
    var air = world;
    if depth >= 1.0 {
        air = uniforms.camera.position + ray * 300.0;
    }
    color = fog(color, ray, air);

    // The grade. An ACES fit rather than a clamp, so the sun's quarter rolls off to
    // white with its colour still in it; gamma after, because the target is linear.
    color = color * 1.0;
    color = clamp(
        (color * (2.51 * color + vec3<f32>(0.03)))
            / (color * (2.43 * color + vec3<f32>(0.59)) + vec3<f32>(0.14)),
        vec3<f32>(0.0),
        vec3<f32>(1.0),
    );
    color = pow(color, vec3<f32>(0.4545));
    // The saturation the curve took out is put back, with a touch more for the greens.
    let luma = dot(color, vec3<f32>(0.2126, 0.7152, 0.0722));
    color = clamp(mix(vec3<f32>(luma), color, 1.22), vec3<f32>(0.0), vec3<f32>(1.0));
    // A gentle S about the middle, to separate a lit culm from a shadowed one.
    color = color * color * (3.0 - 2.0 * color) * 0.32 + color * 0.68;
    // The vignette, light enough to be a lens rather than a frame.
    let centred = in.uv - vec2<f32>(0.5, 0.5);
    color = color * clamp(1.0 - dot(centred, centred) * 0.30, 0.0, 1.0);
    // Grain, last, scaled by brightness so it shows in the mist and not in the blacks.
    let seed = floor(in.uv * size) + vec2<f32>(fract(uniforms.time * 0.37) * 311.0);
    let grain = (hash2(seed) - 0.5) * 0.045 * smoothstep(0.0, 0.26, dot(color, vec3<f32>(0.33)));
    color = color + vec3<f32>(grain);
"#;
