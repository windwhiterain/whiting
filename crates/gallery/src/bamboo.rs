/// The roof's corrugation: the shading normal is rocked along the ridge direction.
///
/// The ridge direction is recovered from the normal itself — a tilted plane's
/// horizontal in-plane direction is the axis it tilts about — so every gable in the
/// scene wears the same tiles whatever way the instance is turned. The gable ends,
/// whose normals are horizontal, are left alone: the gate is where a roof's corrugation
/// belongs and a triangle standing on its point is not tiles.
const ROOF_DISPLACE: &str = r#"
    let ridge_dir = normalize(cross(normal, vec3<f32>(0.0, 1.0, 0.0)));
    let roof_phase = dot(in.world_position, ridge_dir) * 22.0;
    let roof_tilt = sin(roof_phase) * 0.38 * smoothstep(0.25, 0.55, normal.y);
    normal = normalize(normal + ridge_dir * roof_tilt);
"#;

/// What the lighting stage makes of a tile roof.
///
/// The tiles' overlap lines band the texture coordinate the prism carries, the
/// corrugation the normal was rocked by is echoed in the albedo so the valleys between
/// the barrel tiles read darker, and moss creeps in from the eaves where the roof
/// stays damp.
const ROOF_SURFACE: &str = r#"
    let roof_ridge_dir = normalize(cross(normal, vec3<f32>(0.0, 1.0, 0.0)));
    var albedo = vec3<f32>(0.048, 0.056, 0.078)
        * (0.80 + 0.40 * value_noise(in.world_position.xz * 1.3));
    // The tile rows, banded up the slope — only on the slopes: a gable end is the
    // gable wall rising to the roof, lime washed like the walls below it.
    let on_slope = smoothstep(0.25, 0.55, normal.y);
    albedo = mix(vec3<f32>(0.560, 0.530, 0.470), albedo, on_slope);
    let tile_row = fract(in.texture.x * 7.0);
    let row_line = smoothstep(0.00, 0.08, tile_row) * smoothstep(0.22, 0.08, tile_row)
        * on_slope;
    albedo = albedo * (1.0 - row_line * 0.45);
    // The barrel tiles' own shading echo.
    let channel = 0.86 + 0.28 * smoothstep(-1.0, 1.0, sin(dot(in.world_position, roof_ridge_dir) * 22.0 + 1.2));
    albedo = albedo * mix(1.0, channel, smoothstep(0.25, 0.55, normal.y));
    // Moss at the eaves, noise gated so it creeps rather than rules a line.
    let moss = (smoothstep(0.14, 0.02, in.texture.x) + smoothstep(0.86, 0.99, in.texture.x))
        * smoothstep(0.48, 0.78, value_noise(in.world_position.xz * 2.7));
    albedo = mix(albedo, vec3<f32>(0.070, 0.120, 0.042), clamp(moss, 0.0, 1.0) * 0.35);
    color = color * albedo;
"#;

/// What the lighting stage makes of a white wall.
///
/// Lime wash with its mottling, grime where the ground splashes it, and a damp line
/// under the coping drip. The constants are the courtyard's own ground and coping
