/// The noise every stage shares, lattice hashed so it is stable per cell.
const NOISE_WGSL: &str = r#"
/// Returns a value in zero to one from a two dimensional coordinate.
fn hash2(point: vec2<f32>) -> f32 {
    return fract(sin(dot(point, vec2<f32>(127.1, 311.7))) * 43758.5453);
}

/// Returns smooth value noise in zero to one.
fn value_noise(point: vec2<f32>) -> f32 {
    let cell = floor(point);
    let within = fract(point);
    let blend = within * within * (3.0 - 2.0 * within);
    let corner = hash2(cell);
    let east = hash2(cell + vec2<f32>(1.0, 0.0));
    let north = hash2(cell + vec2<f32>(0.0, 1.0));
    let far = hash2(cell + vec2<f32>(1.0, 1.0));
    return mix(mix(corner, east, blend.x), mix(north, far, blend.x), blend.y);
}

/// Returns noise summed over three octaves, in roughly zero to one.
fn fractal(point: vec2<f32>) -> f32 {
    var total = 0.0;
    var amplitude = 0.5;
    var frequency = 1.0;
    for (var octave = 0; octave < 3; octave = octave + 1) {
        total = total + amplitude * value_noise(point * frequency);
        frequency = frequency * 2.1;
        amplitude = amplitude * 0.5;
    }
    return total * 1.14;
}

/// Returns one dimensional value noise in zero to one, for the ridge lines.
fn ridge_noise(value: f32) -> f32 {
    let cell = floor(value);
    let within = fract(value);
    let blend = within * within * (3.0 - 2.0 * within);
    let near = fract(sin(cell * 127.1) * 43758.5453);
    let far = fract(sin((cell + 1.0) * 127.1) * 43758.5453);
    return mix(near, far, blend);
}
"#;

/// The morning sky, as a function of the ray it is seen along.
///
/// This is the one sky: the post stage draws it where no geometry reached, the leaf
/// backlight and the fog's forward scatter read the same sun out of it, and the
/// environment map is generated from its rust mirror. The warm quarter follows the sun
/// around the compass rather than lying everywhere along the horizon, because an
/// even warm band is a sunset filter and this is a morning.
const SKY_WGSL: &str = r#"
/// Returns the colour of the sky along a ray.
fn sky_colour(ray: vec3<f32>) -> vec3<f32> {
    let sun = __SUN_TO__;
    let rise = clamp(ray.y, -1.0, 1.0);
    let flat_ray = ray.xz / max(length(ray.xz), 0.01);
    let flat_sun = sun.xz / length(sun.xz);
    let toward = dot(flat_ray, flat_sun) * 0.5 + 0.5;
    let horizon = mix(vec3<f32>(0.60, 0.66, 0.70), vec3<f32>(0.98, 0.74, 0.46), pow(toward, 3.0));
    let zenith = vec3<f32>(0.15, 0.30, 0.55);
    let below = vec3<f32>(0.42, 0.41, 0.36);
    let above = pow(clamp(rise, 0.0, 1.0), 0.40);
    var sky = select(
        mix(horizon, below, clamp(-rise * 5.0, 0.0, 1.0)),
        mix(horizon, zenith, above),
        rise > 0.0,
    );
    let to_sun = max(dot(ray, sun), 0.0);
    sky = sky + vec3<f32>(1.0, 0.62, 0.34) * (pow(to_sun, 10.0) * 0.22 + pow(to_sun, 60.0) * 1.4);
    sky = sky + vec3<f32>(1.0, 0.78, 0.52) * smoothstep(0.99960, 0.99988, to_sun) * 12.0;
    // A thin morning stratus, stretched along its height and lit by the sun it half
    // hides. Kept faint: it is weather, not the subject.
    if ray.y > 0.02 {
        let sweep = vec2<f32>(ray.x, ray.z) / max(ray.y, 0.10);
        let streak = fractal(sweep * 0.35 + vec2<f32>(uniforms.time * 0.004, 0.0));
        let deck = smoothstep(0.55, 0.78, streak)
            * (1.0 - smoothstep(0.25, 0.60, ray.y))
            * smoothstep(0.02, 0.08, ray.y);
        let lit = pow(to_sun, 2.0);
        let cloud = mix(vec3<f32>(0.60, 0.61, 0.66), vec3<f32>(1.00, 0.78, 0.55), lit);
        sky = mix(sky, cloud, deck * 0.38);
    }
    return sky;
}
"#;

/// The far ranges, drawn where no geometry reached.
///
/// Each line is a function of the ray's azimuth rather than of the pixel, so it stands
/// still when the camera moves. Three layers, each nearer one inked a step deeper than
/// the one behind, because what separates them is the air between them — and the near
/// edge of each dissolves down into the valley's own mist rather than ending at a rule.
const RIDGE_WGSL: &str = r#"
/// Returns the elevation of a ridge line at an azimuth, and which layer it is.
fn ridge_at(azimuth: f32, layer: f32) -> vec2<f32> {
    let swell = ridge_noise(azimuth * (1.7 + layer * 0.9) + layer * 17.0);
    let crest = 1.0 - abs(swell * 2.0 - 1.0);
    let second = 1.0 - abs(ridge_noise(azimuth * (3.9 + layer * 2.1) + layer * 41.0) * 2.0 - 1.0);
    let elevation = 0.016 + layer * 0.024
        + crest * second * (0.030 + layer * 0.026);
    return vec2<f32>(elevation, layer);
}

/// Draws the ridge lines into `sky` along `ray`, nearest last.
fn ridges(sky: vec3<f32>, ray: vec3<f32>) -> vec3<f32> {
    let azimuth = atan2(ray.x, -ray.z);
    var result = sky;
    for (var layer = 2.0; layer >= 0.0; layer = layer - 1.0) {
        let line = ridge_at(azimuth, layer);
        if ray.y < line.x && ray.y > -0.05 {
            let depth_haze = 0.84 - line.y * 0.16;
            let ink = mix(
                vec3<f32>(0.42, 0.48, 0.56),
                vec3<f32>(0.30, 0.37, 0.47),
                line.y * 0.45,
            );
            let top = 1.0 - smoothstep(line.x - 0.006, line.x, ray.y);
            let foot = smoothstep(-0.05, -0.014, ray.y);
            result = mix(result, mix(result, ink, depth_haze), top * foot);
        }
    }
    return result;
}
"#;

/// The valley's mist, as an exponential height fog in closed form.
///
/// The mist pools low — its ceiling wanders with the ground and drifts with the hour —
/// and it scatters towards the sun, so looking into the light over the valley is
/// looking into a blaze and looking away is looking through cool air. The optical
/// depth is taken in closed form rather than stepped, because stepping bands where the
/// mist is thin.
const FOG_WGSL: &str = r#"
/// Returns the world position a pixel shows, given its depth buffer value.
fn world_position(uv: vec2<f32>, depth: f32) -> vec3<f32> {
    let ray = ray_through(uv);
    let eye = uniforms.camera.position;
    let matrix = uniforms.projection.view_projection;
    let row_z = vec4<f32>(matrix[0][2], matrix[1][2], matrix[2][2], matrix[3][2]);
    let row_w = vec4<f32>(matrix[0][3], matrix[1][3], matrix[2][3], matrix[3][3]);
    let at_eye_z = dot(row_z.xyz, eye) + row_z.w;
    let at_eye_w = dot(row_w.xyz, eye) + row_w.w;
    let per_depth = dot(row_z.xyz - depth * row_w.xyz, ray);
    let t = (depth * at_eye_w - at_eye_z) / per_depth;
    return eye + ray * min(t, 2400.0);
}

/// Fogs `color` by the air between the camera and `world`, along `ray`.
fn fog(color: vec3<f32>, ray: vec3<f32>, world: vec3<f32>) -> vec3<f32> {
    let eye = uniforms.camera.position;
    let along = distance(eye, world);
    // The mist's ceiling: low over the valley floor, torn at the edges, drifting.
    let ceiling = 19.0
        + 6.0 * fractal(world.xz * 0.012 + vec2<f32>(uniforms.time * 0.010, 0.0));
    let density = 0.0042;
    let falloff = 0.13;
    let above = max(eye.y - ceiling, 0.0);

    var optical = 0.0;
    if eye.y <= ceiling {
        optical = density * along;
    } else {
        let dip = falloff * ray.y;
        let cross = (ceiling - eye.y) / ray.y;
        if ray.y < -0.0005 && cross < along {
            optical = density * exp(-falloff * above) * (1.0 - exp(-dip * cross)) / dip
                + density * (along - cross);
        } else if abs(dip) > 0.0005 {
            optical = density * exp(-falloff * above) * (1.0 - exp(-dip * along)) / dip;
        } else {
            optical = density * exp(-falloff * above) * along;
        }
    }
    // The aerial perspective proper: even above the mist the air is not nothing.
    optical = optical + along * 0.00028;

    // Forward scatter: the mist blazes about the sun's quarter and stays cool behind.
    let sunward = pow(max(dot(ray, __SUN_TO__), 0.0), 5.0);
    let haze = mix(vec3<f32>(0.60, 0.67, 0.75), vec3<f32>(1.04, 0.72, 0.44), sunward);
    return mix(color, haze, clamp(1.0 - exp(-optical), 0.0, 1.0));
}
"#;

/// What the lighting stage makes of the mountain.
///
/// The pipeline lights the fragment; this body decides what the fragment *is*: meadow
/// on the flats, earth and rock where the slope stands up, swept earth inside the
/// courtyard's own rectangle, and the dark litter ring a bamboo grove keeps around
/// itself. The zones are read off the world position and the normal, so the same body
/// answers for every part of the one heightfield.
const TERRAIN_SURFACE: &str = r#"
    let ground = in.world_position;
    let meadow_noise = fractal(ground.xz * 0.045);
    let close_noise = value_noise(ground.xz * 0.35);

    // The meadow: a green that leans yellow where the grass is dry, patched.
    var albedo = mix(
        vec3<f32>(0.068, 0.120, 0.038),
        vec3<f32>(0.138, 0.158, 0.055),
        meadow_noise,
    );
    albedo = mix(albedo, vec3<f32>(0.175, 0.145, 0.088), smoothstep(0.66, 0.84, close_noise) * 0.30);
    // Higher up the meadow gives way to forest floor, darker and cooler.
    let high = smoothstep(38.0, 85.0, ground.y);
    albedo = mix(albedo, vec3<f32>(0.048, 0.095, 0.038), high * 0.65);

    // Where the slope stands up it is the mountain itself: earth and weathered stone.
    let steep = 1.0 - smoothstep(0.52, 0.78, normal.y);
    let strata = vec3<f32>(0.185, 0.165, 0.135)
        * (0.70 + 0.60 * value_noise(vec2<f32>((ground.x - ground.z) * 0.05, ground.y * 0.8)));
    albedo = mix(albedo, strata, steep);

    // The courtyard's swept earth, and the litter ring the grove keeps: darker, moist,
    // flecked with last year's leaves.
    let from_court = distance(ground.xz, __COURT__);
    let flat = smoothstep(0.78, 0.95, normal.y);
    let court = (1.0 - smoothstep(8.5, 13.0, from_court)) * flat;
    albedo = mix(
        albedo,
        vec3<f32>(0.255, 0.225, 0.175) * (0.84 + 0.32 * value_noise(ground.xz * 0.9)),
        court,
    );
    // Moss creeps in from the walls and the shade, so the yard is swept but not swept
    // clean.
    let moss_yard = smoothstep(0.52, 0.78, value_noise(ground.xz * 0.55 + vec2<f32>(3.7, 9.1)))
        * court;
    albedo = mix(albedo, vec3<f32>(0.105, 0.135, 0.055), moss_yard * 0.55);
    let litter = (1.0 - smoothstep(13.0, 24.0, from_court)) * (1.0 - court) * flat;
    albedo = mix(albedo, vec3<f32>(0.105, 0.088, 0.048), litter * 0.62);

    color = color * albedo * (0.82 + 0.36 * fractal(ground.xz * 0.60));
"#;

/// What the lighting stage makes of a culm.
///
/// The variety hash in `texture.x` mixes a young green with the yellow-green of an old
/// culm, and the node count the geometry was built with bands the shading: a dark thin
/// ring at each node, and the pale powder bloom just above it that a real culm wears.
const CULM_SURFACE: &str = r#"
    let variety = in.texture.x;
    let t = in.texture.y;
    var albedo = mix(
        vec3<f32>(0.100, 0.235, 0.062),
        vec3<f32>(0.260, 0.295, 0.095),
        variety * variety * 0.5,
    );
    // The nodes: dark at the joint, pale powder just above it.
    let node_phase = fract(t * 10.0);
    let ring_dark = smoothstep(0.00, 0.05, node_phase) * smoothstep(0.15, 0.05, node_phase);
    let powder = smoothstep(0.15, 0.21, node_phase) * smoothstep(0.32, 0.21, node_phase);
    albedo = albedo * (1.0 - ring_dark * 0.42) + vec3<f32>(0.055, 0.060, 0.045) * powder;
    // A faint lengthwise streak, so the light runs down a culm the way it runs down a stem.
    albedo = albedo * (0.90 + 0.20 * value_noise(vec2<f32>(variety * 40.0, t * 26.0)));
    color = color * albedo;
"#;

/// How a leaf is lit: the fragment stage's normal is turned towards the eye when the
