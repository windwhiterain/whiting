/// How far the terrain reaches from its centre, in world units (metres, roughly).
const EXTENT: f64 = 280.0;

/// How many cells the terrain is divided into along each axis.
///
/// The courtyard platform is flattened smooth, so the grid's business is the mountain,
/// and a mountain reads at two and a half metres a cell. Finer buys nothing the frame
/// can resolve and the compile pays for it.
const DIVISIONS: usize = 240;

/// The height of the courtyard platform, cut flat into the slope.
const GROUND: f64 = 27.5;

/// The courtyard's centre on the map.
const COURT: [f64; 2] = [0.0, 0.0];

/// The direction **towards** the sun: east-south-east and low, an hour after sunrise,
/// so every culm throws a long shadow across the meadow and the morning is in the light.
///
/// This is the one fact every stage shares. It is formatted into the WGSL once, the
/// directional light travels along its negative, and the environment map is generated
/// from the same constant — so the glow in the sky, the warmth in the mist, the
/// backlight through the leaves and the light on the wall are one sun.
const SUN_TO: [f64; 3] = [0.82, 0.30, 0.28];

/// The house's footprint centre: standing at the back of the yard, facing south.
const HOUSE: [f64; 3] = [0.0, GROUND, -7.2];
/// The house's walls: width, height, depth.
const HOUSE_WALLS: [f64; 3] = [7.2, 3.4, 4.6];

/// The gate's centre on the south wall, a touch east of the house's axis.
const GATE: [f64; 2] = [2.5, 8.0];

/// Builds the scene.
pub fn bamboo() -> Value {
    let sun_to = normalized(SUN_TO);
    let helpers = fill(&[NOISE_WGSL, SKY_WGSL].concat());
    let mut shaders = mesh_shaders("", &helpers);
    shaders.push(displaced_lighting_shader(
        "lighting_terrain",
        "",
        &fill(TERRAIN_SURFACE),
        &helpers,
    ));
    shaders.push(displaced_lighting_shader(
        "lighting_culm",
        "",
        &fill(CULM_SURFACE),
        &helpers,
    ));
    shaders.push(displaced_lighting_shader(
        "lighting_leaf",
        LEAF_DISPLACE,
        &fill(LEAF_SURFACE),
        &helpers,
    ));
    shaders.push(displaced_lighting_shader(
        "lighting_roof",
        ROOF_DISPLACE,
        &fill(ROOF_SURFACE),
        &helpers,
    ));
    shaders.push(displaced_lighting_shader(
        "lighting_wall",
        "",
        &fill(WALL_SURFACE),
        &helpers,
    ));
    shaders.push(emission_shader("lantern_glow", LANTERN_GLOW, &helpers));
    shaders.push(post_shader(
        &fill(GRADE),
        &fill(&[NOISE_WGSL, SKY_WGSL, RIDGE_WGSL, FOG_WGSL].concat()),
    ));

    let (materials, instances) = build_instances();

    Value::structure([
        ("name".to_owned(), Value::String("bamboo".to_owned())),
        ("time".to_owned(), Value::Float(0.0)),
        (
            "frame".to_owned(),
            Value::structure([
                ("width".to_owned(), Value::Int(1536)),
                ("height".to_owned(), Value::Int(1024)),
                // The sun's page covers the courtyard and the near grove at a seventh of
                // a metre a texel: bamboo shadows on the white wall are the picture, and
                // a coarse page turns them to porridge. Four pages is the sun, the
                // lantern light and two spare.
                ("shadow_page_width".to_owned(), Value::Int(2048)),
                ("shadow_page_height".to_owned(), Value::Int(2048)),
                ("shadow_pages".to_owned(), Value::Int(4)),
            ]),
        ),
        ("cameras".to_owned(), Value::List(cameras())),
        (
            "images".to_owned(),
            Value::List(vec![image("morning", 64, 64, morning_pixels(64))]),
        ),
        (
            "lights".to_owned(),
            Value::List(vec![
                // The sun. A directional light because a morning sun over a valley is
                // parallel for everything this frame shows, and its page is fitted to the
                // middle of the scene — which is the courtyard, where the shadows matter.
                directional(
                    "sun",
                    [-sun_to[0], -sun_to[1], -sun_to[2]],
                    [1.0, 0.87, 0.68],
                    2.35,
                    95.0,
                ),
                // The sky, as an environment map generated from the same sky function the
                // post stage draws: the ambient a shadowed wall receives *is* the sky.
                environment_light("morning", "morning", [1.0; 3], 0.72),
                // The lanterns at the gate, still burning in the morning. Warm, small,
                // and nearly lost in the sun — which is what a lantern at dawn is.
                // The lanterns at the gate, still burning in the morning. Warm, small,
                // and nearly lost in the sun — which is what a lantern at dawn is. Its
                // reach stops at the gatehouse, or it paints the whole yard orange.
                light_with_radius(
                    "lantern",
                    [GATE[0], GROUND + 2.2, GATE[1] + 0.6],
                    [1.0, 0.30, 0.10],
                    0.9,
                    6.0,
                    7.0,
                ),
            ]),
        ),
        ("shaders".to_owned(), Value::List(shaders)),
        ("meshes".to_owned(), Value::List(build_meshes())),
        (
            "screen_materials".to_owned(),
            Value::List(vec![screen_material("post", "post")]),
        ),
        ("post_processes".to_owned(), post_processes(&["post"])),
        ("mesh_materials".to_owned(), Value::List(materials)),
        ("instances".to_owned(), instances),
    ])
}

