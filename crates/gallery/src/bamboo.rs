//! 中国山村竹林小院 — a walled courtyard under a bamboo grove, on a misty mountain slope.
//!
//! The picture is a place, not a model: a white-walled farmhouse with a dark tile roof,
//! a yard wall with a gatehouse and two lanterns still burning at first light, a stone
//! path that comes up the slope through the bamboo, and ranges behind ranges standing
//! in the morning haze. What makes it read as a photograph of a mountain village rather
//! than as geometry is five decisions, all of them the scene's:
//!
//! - **The bamboo is grown, not placed.** Every culm is a curved, tapering, node-ringed
//!   tube with a per-stalk hash carried in its texture coordinate, and the leaves are
//!   blades fanned off the top nodes of the same stalk. The whole grove is two meshes —
//!   culms and leaves — because a pass draws one instance and the pass count is the
//!   render cost. Culms lean, and the ones at the grove's edge lean over the yard wall,
//!   which is where the picture's foreground comes from.
//! - **The tile roofs are shaded, not modelled.** A roof prism's normal is corrugated in
//!   the fragment stage along the ridge direction — which is recovered from the normal
//!   itself, so every gable in the scene wears the same tiles whatever way it is turned —
//!   and the overlap lines of the tile rows are banded in the texture coordinate the
//!   prism already carries.
//! - **One morning, told once.** The sun's bearing is a single rust value formatted into
//!   the light, the sky, the leaf backlight, the fog scatter and the environment map the
//!   ambient term is read from. The map is generated by evaluating the *same* sky
//!   function on the CPU, so the sky a fragment sees and the sky a shadow is lit by
//!   cannot drift apart.
//! - **Depth is weather.** Mist pools in the valley below the yard, the far ranges are
//!   drawn by the post stage where no geometry reached, and the aerial haze between the
//!   eye and a far slope is most of what a mountain morning is made of.
//! - **The courtyard is lived in.** Jars against the house wall, a stone table with two
//!   stools, tea shrubs along the south wall, doors ajar — the smallness is the subject
//!   as much as the mountain is.

