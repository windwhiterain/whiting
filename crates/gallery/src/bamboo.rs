/// The height of the land before the courtyard platform is cut.
///
/// A slope falling south into a valley, gathered up at the back into a creased range,
/// walled east and west by lower wooded hills, and a soft rise across the valley's
/// mouth so the southern horizon has a body behind the mist.
fn land_height(x: f64, z: f64) -> f64 {
    // The long fall, north to south, steepening into the mountain at the back.
    let fall = (z + EXTENT) / (2.0 * EXTENT);
    let base = 6.0 + 52.0 * (1.0 - fall).powf(1.6);

    // The range at the back. Creased noise rather than smooth, because a skyline is a
    // line of crests and saddles; a one dimensional profile along the ridge line so the
    // crest wanders along it.
    let ridge_profile = fractal_noise([(x + 80.0) * 0.012, 0.6], 5, 131);
    let ramp = smoothstep(-50.0, -EXTENT, z);
    let creased = ridged_noise([x * 0.016, z * 0.011], 5, 139);
    let mass = ramp * (30.0 + 85.0 * ridge_profile) * (0.35 + 0.9 * creased);

    // The side hills, kept low and creased so they never read as cones.
    let wall_west = smoothstep(120.0, EXTENT, -x)
        * (10.0 + 30.0 * ridged_noise([z * 0.020, x * 0.014], 4, 47));
    let wall_east = smoothstep(130.0, EXTENT, x)
        * (10.0 + 26.0 * ridged_noise([z * 0.018 + 9.0, x * 0.013], 4, 53));

    // The far side of the valley, low and soft: a body for the mist to lie against,
    // low enough that the post stage's ridge lines stand above it.
    let south = smoothstep(150.0, EXTENT, z)
        * (3.0 + 10.0 * ridged_noise([x * 0.012, z * 0.010], 4, 91));

    // The undulation that keeps a meadow from being a ramp. Faded where the mountain
    // takes over, where five metres of wrinkle is nothing.
    let undulation = (1.0 - smoothstep(30.0, 90.0, base + mass))
        * 5.0
        * fractal_noise([x * 0.020, z * 0.020], 3, 77);

    base + mass + wall_west + wall_east + south + undulation
}

/// The height of the terrain: the land, with the courtyard's bench cut flat into it.
fn terrain_height(x: f64, z: f64) -> f64 {
    let land = land_height(x, z);
    let yard = ((x - COURT[0]).powi(2) + (z - COURT[1]).powi(2)).sqrt();
    // The bench: flat where the yard stands, eased into the slope over twice that, so
    // the bank below the south wall is a bank and not a wall.
    let bench = 1.0 - smoothstep(15.0, 34.0, yard);
    land + (GROUND - land) * bench
}

/// The slope of the terrain at a point, by central difference.
fn terrain_slope(x: f64, z: f64) -> f64 {
    let step = 2.0 * EXTENT / DIVISIONS as f64;
    let dx = terrain_height(x + step, z) - terrain_height(x - step, z);
    let dz = terrain_height(x, z + step) - terrain_height(x, z - step);
    (dx * dx + dz * dz).sqrt() / (2.0 * step)
}

/// A smoothstep, matching the WGSL builtin's shape.
fn smoothstep(low: f64, high: f64, value: f64) -> f64 {
    let t = ((value - low) / (high - low)).clamp(0.0, 1.0);
    t * t * (3.0 - 2.0 * t)
}

