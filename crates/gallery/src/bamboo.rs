    albedo = albedo * (0.94 + 0.11 * value_noise(in.world_position.xz * 4.4 + in.world_position.yy * 3.1));
    // The ground's splash and the damp foot.
    let foot = smoothstep(__GROUND__ + 0.85, __GROUND__ + 0.05, in.world_position.y);
