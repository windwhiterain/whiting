/// Writes a whole scene document.
///
/// The images the world refers to come back with it, so that a caller writing the document to
/// disk writes them beside it: the loader resolves `filename` against the document's own
/// directory, so the two have to land in the same place.
pub fn write(
    scene: &Value,
    options: &EmitOptions,
    report: &mut LossyReport,
) -> EmitResult<(String, Vec<SceneImage>)> {
    let fields = scene.as_field_map().ok_or_else(|| EmitError::Malformed {
        detail: "the scene is not a structure".to_owned(),
    })?;

    // Everything is read before anything is written, so a scene refused in `Reject` leaves no
    // half-written document for someone to find and try to debug.
    let meshes = geometry::read_meshes(
        read::list_or_empty(fields, "meshes", "the scene")?,
        options.lossy,
        report,
    )?;
    let materials = material::read_materials(
        read::list_or_empty(fields, "mesh_materials", "the scene")?,
        options.lossy,
        report,
    )?;
    let lights = read_lights(
        read::list_or_empty(fields, "lights", "the scene")?,
        options.lossy,
        report,
    )?;
    let instances = read_instances(fields)?;
    let camera = read_camera(fields)?;
    // A material names a shader **by label**, not by stage, so the stage has to be looked up
    // through the shader entries. Reading the material's own `shader` field as if it were a stage
    // is a category error that happens to look right for a scene whose shaders happen to be named
    // after their stage — which is every scene in the gallery, and none of the ones written by
    // hand.
    let stages = read_shader_stages(fields);

    let mut writer = Writer::new();

    writer.comment("Generated by whiting. Do not edit; re-emit from the scene document.");
    settings::write_film(&mut writer, settings::exposure(scene, options.exposure));
    settings::write_integrator(&mut writer, options);
    write_camera(&mut writer, &camera);
    let images = referenced_images(fields, &lights);
    let mut referenced = Vec::new();
    write_world(
        &mut writer,
        &lights,
        &images,
        &mut referenced,
        options.lossy,
        report,
    )?;
    let drawn = write_materials(&mut writer, &materials, &stages, options.lossy, report)?;
    write_lights(&mut writer, &lights);
    write_instances(&mut writer, &instances, &meshes, &materials, &drawn)?;

    // Only the images the world actually referred to are returned. An image the document carries
    // but nothing names — a tile texture, say — belongs to the rasterised path, and writing it
    // beside the document would put a file there for a reason nobody can read off the file name.
    let wanted: Vec<SceneImage> = images
        .into_iter()
        .filter(|image| referenced.contains(&image.label))
        .collect();
    Ok((writer.finish(), wanted))
}

/// Reads every light, honouring the lossy mode.
///
/// A light with no `light_type` mapping is refused in [`LossyMode::Reject`] and recorded in
/// [`LossyMode::Degrade`]. In the degrading case the frame still renders, with that light
/// simply not in it, which is a materially different image rather than a marginally worse
/// one — so the report is the only thing standing between an author and a scene that
/// renders without the light they wrote.
fn read_lights(
    lights: &[Value],
    mode: LossyMode,
    report: &mut LossyReport,
) -> EmitResult<Vec<Light>> {
    let mut out = Vec::with_capacity(lights.len());
    for value in lights {
        match light::read_light(value) {
            Ok(light) => out.push(light),
            Err(EmitError::Unsupported(UnsupportedField::Light { kind })) => {
                light::reject_or_record(&kind, mode, report)?;
            }
            Err(error) => return Err(error),
        }
    }
    Ok(out)
}

/// Writes every punctual light.
///
/// The environment light is skipped here because [`write_world`] has already written it into
/// the `<background>` element, and the loader has one world and no second place to put
/// another.
///
/// A light is written inside its own transform scope rather than the world's, so that its
/// position and orientation compose the way an instance's do. A directional light has no
/// position, so it takes only a rotation, and the negative Z of that rotation is the way the
/// light travels — which was confirmed by rendering a sun with no rotation, where it lit
/// faces pointing along its own axis.
fn write_lights(writer: &mut Writer, lights: &[Light]) {
    let punctual: Vec<&Light> = lights
        .iter()
        .filter(|light| light.kind != "background")
        .collect();
    if punctual.is_empty() {
        return;
    }
    writer.comment("Lights");
    for light in punctual {
        light::write_light(writer, light);
    }
}

fn list<'a>(fields: &'a FieldMap, name: &str) -> EmitResult<&'a [Value]> {
    read::list_or_empty(fields, name, "the scene")
}

/// One instance: which mesh, where, drawn by which material.
struct Instance {
    label: String,
    mesh: String,
    material: String,
    transform: Transform,
}

/// Reads a scene's instances.
///
/// # Why this accepts two shapes
///
/// Our scene language buckets instances **by the pass that draws them**: `kit::instances` builds
/// a dictionary whose keys are pass suffixes and whose values are lists, because the same mesh
/// placed in two passes is two instances and the rasteriser walks the buckets. A document written
/// by hand may instead hold one flat list, and both are the same scene language — the bucketing is
/// what a *pass* needs, not what a scene means.
///
/// The target format has no passes, so the buckets are flattened here: one geometry list with
/// every instance in it. A mesh that appears in two buckets is written twice, which is correct —
/// they are two placements of it — and each is wrapped in its own material scope, so the two
/// draw with the two materials their buckets asked for.
///
/// A flat list is read as a single unnamed bucket rather than as an error, because a caller that
/// wrote one has said everything there is to say and refusing it would buy nothing.
fn read_instances(fields: &FieldMap) -> EmitResult<Vec<Instance>> {
    let Some(value) = read::field(fields, "instances") else {
        return Ok(Vec::new());
    };
    let mut out = Vec::new();

    // A flat list is the simple shape and is read first, so a document that is a list never
    // reaches the dictionary branch below.
    let buckets: Vec<&[Value]> = if let Some(entries) = value.as_list() {
        vec![entries]
    } else if let Some(bucketed) = value.as_dict() {
        let mut collected: Vec<&[Value]> = Vec::with_capacity(bucketed.len());
        for (_, bucket) in bucketed {
            let entries = bucket.as_list().ok_or_else(|| EmitError::Malformed {
                detail: "an instance bucket is not a list".to_owned(),
            })?;
            collected.push(entries);
        }
        collected
    } else {
        return Err(EmitError::Malformed {
            detail: format!(
                "the scene's 'instances' is {}, and it is either a list of instances or a \
                 dictionary of pass to instances",
                value.kind_name()
            ),
        });
    };

    for entries in buckets {
        for entry in entries {
            let instance_fields = entry.as_field_map().ok_or_else(|| EmitError::Malformed {
                detail: "an instance is not a structure".to_owned(),
            })?;
            let label = read::text_field(instance_fields, "label", "an instance")?;
            out.push(Instance {
                mesh: read::text_field(instance_fields, "mesh", &format!("instance '{label}'"))?,
                material: read::text_field(
                    instance_fields,
                    "material",
                    &format!("instance '{label}'"),
                )?,
                transform: transform::read_transform(
                    read::field(instance_fields, "transform"),
                    &format!("instance '{label}'"),
                )?,
                label,
            });
        }
    }
    Ok(out)
}

/// The camera: where it stands, which way it looks, and what it can see.
struct Camera {
    transform: Transform,
    /// The angle the loader's camera node takes, in radians.
    ///
    /// The node's one socket is a full angle along the frame's **longer** side, which is not the
    /// side this engine measures a camera's angle on — see [`angle_along_the_longer_side`].
    field_of_view: f64,
    width: usize,
    height: usize,
}

/// The angle the loader's camera node takes, from an angle this engine measures vertically.
///
/// # Invariants
///
/// The node carries **one** angle and applies it along the frame's longer side, where the sensor
/// fit is automatic. This engine measures `field_of_view` **down the frame**, and the schema says
/// so: `field_of_view` is "the angle seen through, vertically", and a lens is a width, so
/// `vertical_field_of_view` divides the horizontal tangent by the aspect to reach it.
///
/// So the two are the same angle on different axes, and which one the node wants is the frame's
/// aspect and nothing else:
///
/// - **wider than tall** — the longer side is the horizontal, which is the side a sensor is
///   named on, so the angle widens by the aspect;
/// - **taller than wide** — the longer side is the vertical, which is already what this engine
///   measures, so it is the angle unchanged.
///
/// Getting this backwards is not a small error: measured against `foldyard`, whose first camera
/// is a thirty five millimetre lens on a full frame negative and names no angle at all, the
/// ninety degree default this replaced was **1.94 times** the half angle of the lens the scene
/// asked for, and the frame came back with the yard's wall a third of the size it is drawn at
/// elsewhere in this workspace.
fn angle_along_the_longer_side(vertical: f64, aspect: f64) -> f64 {
    if aspect >= 1.0 {
        2.0 * ((vertical / 2.0).tan() * aspect).atan()
    } else {
        vertical
    }
}

/// Reads the camera.
///
/// # Why the transform is built rather than read
///
/// Our document states a camera as an **eye and a target** — `kit::camera_placed` writes
/// `eye`, `target`, `field_of_view`, `near` and `far`, and no transform at all. Reading a
/// `transform` field that no camera has ever carried returned the identity, so the camera was
/// emitted at the origin with its subject around it, and the render came back with no error and
/// a black frame.
///
/// So the eye becomes the translation and the eye-to-target direction becomes the rotation. The
/// loader's camera looks along its own **`+Z`**, established by moving the camera and watching
/// the geometry appear — see [`camera_rotation`].
///
/// # The angle and the size are both read from where the document writes them
///
/// Both were read from the **camera**, and a camera in this workspace's schema has neither.
///
/// - **the size** is the **scene's** `frame`, a field of the scene and not of a camera. Reading
///   it off the camera found nothing on any camera that has ever been written and fell back to
///   `1920 x 1080`, so every scene was rendered at a shape it did not ask for. Measured:
///   `foldyard` names `1536 x 1024` and was rendered `1920 x 1080`.
/// - **the angle** is `field_of_view` **or** `focal_length` against `sensor_width`, and the
///   precedence between them belongs to the rasterised path's camera reader rather than to a
///   second opinion here. `vertical_angle` is that reader's own function.
///
/// A camera with no eye is not built by guessing: it is reported, because a camera that cannot
/// see anything is not a camera with a default.
fn read_camera(fields: &FieldMap) -> EmitResult<Camera> {
    // The frame bounds nothing here: this backend writes a picture into a file and has no
    // texture to allocate, so the ceiling is the one that is not a ceiling.
    let (frame, _) = Frame::read_declared(
        fields.get(FRAME).and_then(Value::as_field_map),
        DeviceLimits::unbounded(),
    );
    let aspect = frame.aspect();
    let cameras = list(fields, "cameras")?;
    let Some(first) = cameras.first() else {
        return Ok(Camera {
            transform: Transform::identity(),
            field_of_view: angle_along_the_longer_side(DEFAULT_FIELD_OF_VIEW, aspect),
            width: frame.width.max(1) as usize,
            height: frame.height.max(1) as usize,
        });
    };
    let camera_fields = first.as_field_map().ok_or_else(|| EmitError::Malformed {
        detail: "a camera is not a structure".to_owned(),
    })?;

    // A document that does carry a transform is taken at its word, so a hand-written camera
    // placed by matrix still works; the eye/target reading is what a document written by this
    // workspace's own kit needs.
    let transform = match read::field(camera_fields, "transform") {
        Some(_) => {
            transform::read_transform(read::field(camera_fields, "transform"), "the camera")?
        }
        None => {
            let eye = read::field(camera_fields, "eye")
                .map(|value| read::triple(value, "the camera's eye"));
            let Some(eye) = eye else {
                return Err(EmitError::Malformed {
                    detail: "the camera states neither a transform nor an eye".to_owned(),
                });
            };
            let eye = eye?;
            let target = match read::field(camera_fields, "target") {
                Some(value) => read::triple(value, "the camera's target")?,
                None => [0.0; 3],
            };
            Transform {
                translation: eye,
                rotation: camera_rotation(eye, target),
                scale: [1.0; 3],
            }
        }
    };

    Ok(Camera {
        transform,
        field_of_view: angle_along_the_longer_side(vertical_angle(Some(first), aspect), aspect),
        width: frame.width.max(1) as usize,
        height: frame.height.max(1) as usize,
    })
}

/// The Euler angles that turn a camera's `+Z` onto the direction from its eye to its target.
///
/// # The camera looks along `+Z`, and the geometry decided that
///
/// Measured, with the geometry held still and only the camera moved. A camera at
/// `translate="0, 0, -6"` with no rotation renders the geometry in its material's colour; the
/// same document with the camera at `translate="0, 0, 6"` renders nothing but the world
/// background, and needs `rotate="180, 0, 1, 0"` to see it. Both ran to completion with no
/// error, so this is not a load failure — at identity the camera faces `+Z`, and the geometry
/// lies in the `-Z` direction from a camera standing on the positive side.
///
/// The rotation wanted is therefore the one that carries `+Z` onto `normalize(target - eye)`,
/// which is `delta` itself rather than its negation.
///
/// # The first angle is **negated**, and the render is what proved it
///
/// A right-handed turn about `+X` carries `+Z` to `(0, -sin a, cos a)`, so a positive first
/// angle tilts the camera's view **down**. The elevation of the target above the eye is
/// therefore written negated, and a target below the eye produces a negative number here.
///
/// Measured on the `tiles` scene, whose camera stands at `(0, 0.7, 2.6)` and looks at
/// `(0, 0.1, -8)`. That target is 3.24 degrees **below** the eye. The pitch written without the
/// negation is `-3.24`, which composes to an axis-angle of `180, 0, 0.9996, 0.0283` — a half
/// turn about an axis tilted 1.62 degrees towards `+Z`, which carries the camera's `+Z` to
/// `(0, +0.0566, -0.9984)`. It looked 3.24 degrees **up**. The frame came back with the floor
/// occupying the bottom two fifths instead of the middle, and the horizon above centre rather
/// than below it. The rasterised path renders the same document with the horizon in the right
/// place, so the two backends agreed on the scene and disagreed on the transform.
///
/// # Invariants
///
/// The eye and the target are points, so their difference is normalised before any angle is taken
/// from it: a target is a place in the scene and not a direction, and the distance between the
/// two must not change where the camera points.
///
/// An eye and a target that coincide leave the rotation at zero rather than producing a NaN,
/// which is a camera that cannot see rather than a document that cannot be read.
fn camera_rotation(eye: [f64; 3], target: [f64; 3]) -> [f64; 3] {
    let delta = [target[0] - eye[0], target[1] - eye[1], target[2] - eye[2]];
    let length = (delta[0].powi(2) + delta[1].powi(2) + delta[2].powi(2)).sqrt();
    if length < 1e-9 {
        return [0.0; 3];
    }
    let forward = [delta[0] / length, delta[1] / length, delta[2] / length];
    let yaw = forward[0].atan2(forward[2]);
    let horizontal = (forward[0].powi(2) + forward[2].powi(2)).sqrt();
    let pitch = forward[1].atan2(horizontal);
    [-pitch.to_degrees(), yaw.to_degrees(), 0.0]
}

/// The size the document's camera asks the image to be, in pixels.
///
/// # Why the caller has to be told
///
/// The loader reads `width` and `height` off the `<camera>` element and applies them to the
/// camera, but the **buffer it renders into is the size of the command line's** `--width` and
/// `--height`. Measured: a document whose camera says `1920, 1080` and whose film says nothing
/// about resolution renders at `1024, 512`, which is neither the document's nor the default;
/// the same run with `--width 320 --height 180` writes a `320, 180` png. The film node has no
/// resolution socket at all (`src/scene/film.cpp`, `NODE_DEFINE(Film)`), so there is nowhere in
/// the document to put it and the only way through is the process's own arguments.
///
/// The size is therefore read here, through the same [`read_camera`] that writes it, rather than
/// at the call site: a second reader of the camera would be a second thing to keep in step with
/// the first.
pub fn render_size(scene: &Value) -> EmitResult<(u32, u32)> {
    let fields = scene.as_field_map().ok_or_else(|| EmitError::Malformed {
        detail: "the scene is not a structure".to_owned(),
    })?;
    let camera = read_camera(fields)?;
    Ok((camera.width as u32, camera.height as u32))
}

/// Writes the camera inside its transform scope.
///
/// # The camera's frame is mirrored, and the mirror is not optional
///
/// Cycles draws the camera's own `+X` on the **right** of the frame: `rastertocamera` is
/// `screentocamera * rastertoscreen` (`src/scene/camera.cpp:265`), both factors are positive
/// diagonals (`src/scene/camera.cpp:236-249`), so a point on the `+X` side of the view axis
/// lands at a larger raster `x`. Measured on a document that holds nothing but the camera and
/// three triangles: world `+X` rendered at `x = 0.027` and world `-X` at `x = 0.969`.
///
/// A camera whose `+X` is its own right-hand side is therefore **left-handed**, because its `+Z`
/// is the direction it looks along. For orthonormal columns `a, b, c` of a rotation,
/// `b × c = det · a`, so `a = cross(c, b) = cross(forward, up)` — the right-hand side — forces
/// `det = -1`. Measured on `landscape`: the basis written here had `det = +1` with
/// `localX = cross(up, forward)`, the right-hand side's **opposite**, and two markers set on the
/// raster camera's right and left came out of Cycles at `x = 0.240` and `x = 0.818` — exchanged.
///
/// No rotation can stand in for the reflection: one about the view axis flips right **and** up,
/// and one about `up` turns the camera away from its target. Both were measured. So it rides in
/// the transform's `scale`, which the loader applies after `rotate`
/// (`src/app/cycles_xml.cpp:706-710`), negating the local `X` column and leaving `Y`, `Z` and
/// the translation untouched. Cycles keeps the camera matrix verbatim — `set_matrix` is the
/// generated socket setter over `NODE_SOCKET_API(Transform, matrix)`
/// (`src/scene/camera.h:151`) — so the negative determinant reaches the kernel unaltered.
///
/// # The size is not the size of the image
///
/// The `width` and `height` on the camera element are the camera's own view plane, and the
/// loader reads them — but they are **not** the size of the image, which comes from the command
/// line's `--width` and `--height`. Measured: this element saying `1920, 1080` renders a
/// `1024, 512` png, and the same document at `--width 320 --height 180` renders a `320, 180`
/// one. They are written because they are what the camera node states, and because a reader of
/// the document is entitled to see the size the scene asked for; [`render_size`] is how a caller
/// gets it out to the process.
fn write_camera(writer: &mut Writer, camera: &Camera) {
    writer.comment("Camera");
    // The loader reads `width`, `height` and the camera's own sockets from the `<camera>`
    // element, and takes the transform from the enclosing scope, so the camera is a sibling
    // of the transform rather than a child of it. `xml_read_camera` calls `cam->set_matrix`
    // with `state.tfm` and never looks at the element's own transform attributes.
    writer.open(
        "transform",
        &transform_attributes(
            &cycles_camera_frame(&camera.transform),
            axes::Rotation::Frame,
        ),
    );
    writer.leaf(
        "camera",
        &[
            ("width", camera.width.to_string()),
            ("height", camera.height.to_string()),
            ("type", "perspective".to_owned()),
            ("fov", camera.field_of_view.to_string()),
        ],
    );
    writer.close("transform");
}

/// A camera's transform with the mirror Cycles' camera frame needs.
///
/// # Why it lands on `scale`
///
/// The loader composes `translate`, then `rotate`, then `scale`
/// (`src/app/cycles_xml.cpp:694-710`), so a scale written last multiplies the rotation's columns
/// from the right and reaches the frame rather than the world. Negating the local `X` is the
/// whole of it; see [`write_camera`] for the measurement that forces the sign.
///
/// # Why it is not folded into `read_camera`
///
/// Both routes into a camera — an eye and a target, or a transform written by hand — mean the
/// same thing in this engine's axes, and only this function knows Cycles reads a camera's frame
/// mirrored. Applying it where the camera is specified would leave a second route that has to
/// remember, which is where the mirror came from the first time.
fn cycles_camera_frame(transform: &Transform) -> Transform {
    Transform {
        scale: [-transform.scale[0], transform.scale[1], transform.scale[2]],
        ..*transform
    }
}

/// Writes the world.
///
/// Only one environment light is written, and only when the scene has one. Cycles takes the
/// world from a single `<background>` element, so a second environment light would have
/// nowhere to go; the scene document already refuses a second one.
///
/// # An image is written out as a file, because the format has nowhere to put the bytes
///
/// `environment_light` names its image by **label**, the same way a material does, because the
/// pixels are in the document's own `images` list. The loader wants a **path**: it opens
/// whatever `filename` names, and reports `Image file <path> does not exist` when that is not a
/// file, then renders the rest of the scene and exits zero.
///
/// So the label is written as a file name and the bytes go beside the document. It resolves
/// relative to the document's own directory, which is what the loader does with it -- measured,
/// an `air` in a document at `out/scene.xml` was reported as `out/air` -- which is why the
/// emitted name is not a path and why the two must be written to the same place.
///
/// This used to write the label unchanged, so every environment image was a missing file. It
/// was not visible: `foldyard` and `tidewater` both name one, both rendered a complete and
/// plausible frame with no sky in it, and neither printed anything the exit status reflected.
///
/// # The colour is part of the strength, not left out
///
/// The rasterised path samples the map and multiplies by the light's own colour and radiance:
/// `textureLoad(...) * uniforms.environment.rgb`, with the radiance already folded into that
/// `rgb`. The loader's `<background>` has a `color` socket, but connecting a texture onto it
/// **replaces** it, so the tint has nowhere to live except the strength, which multiplies what
/// the texture produces. Writing the radiance alone would render every tinted sky untinted.
fn write_world(
    writer: &mut Writer,
    lights: &[Light],
    images: &[SceneImage],
    referenced: &mut Vec<String>,
    mode: LossyMode,
    report: &mut LossyReport,
) -> EmitResult<()> {
    let Some(environment) = lights.iter().find(|light| light.kind == "background") else {
        return Ok(());
    };
    writer.comment("World");
    writer.open_bare("background");
    match &environment.image {
        Some(label) => {
            // A name is written either way. When the document carries no such image the loader
            // is left to report the missing file, which names it; dropping the element instead
            // would produce a scene with no world and no explanation of why. Only an image
            // that is actually carried is queued to be written, so the caller is never asked
            // to write bytes that do not exist.
            writer.leaf(
                "environment_texture",
                &[
                    ("name", "world_texture".to_owned()),
                    ("filename", name_for(label)),
                ],
            );
            if images.iter().any(|image| image.label == *label) {
                referenced.push(label.clone());
            }
            // Refused here rather than converted, and honoured by the lossy mode. Converting
            // would put a second definition of how a map is laid out inside the emitter, which
            // is the failure this case exists to prevent.
            if let Some(image) = images.iter().find(|image| image.label == *label) {
                if !image.projection.is_readable() {
                    match mode {
                        LossyMode::Reject => {
                            return Err(EmitError::Unsupported(
                                super::error::UnsupportedField::ImageProjection {
                                    image: label.clone(),
                                    projection: image.projection.tag().to_owned(),
                                },
                            ));
                        }
                        LossyMode::Degrade => {
                            report.record(super::error::UnsupportedField::ImageProjection {
                                image: label.clone(),
                                projection: image.projection.tag().to_owned(),
                            });
                        }
                    }
                }
            }
            writer.leaf(
                "background",
                &[
                    ("name", "world".to_owned()),
                    ("strength", environment_strength(environment)),
                ],
            );
            writer.leaf(
                "connect",
                &[
                    ("from", "world_texture color".to_owned()),
                    ("to", "world color".to_owned()),
                ],
            );
            writer.leaf(
                "connect",
                &[
                    ("from", "world background".to_owned()),
                    ("to", "output surface".to_owned()),
                ],
            );
        }
        None => {
            writer.leaf(
                "background",
                &[
                    ("name", "world".to_owned()),
                    (
                        "color",
                        Writer::color(
                            environment.color[0],
                            environment.color[1],
                            environment.color[2],
                        ),
                    ),
                    ("strength", environment_strength(environment)),
                ],
            );
            writer.leaf(
                "connect",
                &[
                    ("from", "world background".to_owned()),
                    ("to", "output surface".to_owned()),
                ],
            );
        }
    }
    writer.close("background");
    Ok(())
}

/// The `strength` of a world, as a colour: the light's own tint scaled by its radiance.
///
/// The same multiplication a punctual light gets, for the same reason and with the same
/// hazard — it was missing here, so a scene's tinted environment rendered untinted.
fn environment_strength(environment: &Light) -> String {
    Writer::color(
        environment.color[0] * environment.strength,
        environment.color[1] * environment.strength,
        environment.color[2] * environment.strength,
    )
}

/// The name an environment image is written under and referred to by.
///
/// # The name is not a path, and that is load-bearing
///
/// The loader resolves `filename` against **the document's own directory** — measured, an `air`
/// in a document at `out/scene.xml` was reported as `out/air`. So the emitted name has to be
/// bare, and the bytes have to be written to the same directory as the document. A path here
/// would resolve against the document's directory too, and be wrong twice over for anything not
/// sitting right beside it.
fn name_for(label: &str) -> String {
    format!("{label}.png")
}

/// One image the document carries, in the form the world needs it.
pub struct SceneImage {
    pub label: String,
    pub width: u32,
    pub height: u32,
    pub projection: ImageProjection,
    pub pixels: Vec<u8>,
}

/// How a direction is turned into a texel of an image.
///
/// Only the one a path tracer reads is carried. The other is **refused**, and refusing is the
/// point: a scene whose sky is an octahedral map and an exporter that read it as a latlong one
/// would together produce a complete frame with half a sky in it, and nothing in the output would
/// say which of the two was wrong. A scene that wants a sky everywhere declares a latlong map.
#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
pub enum ImageProjection {
    /// The rectangle, twice as wide as tall. The default, and the only one the loader reads.
    #[default]
    Latlong,
    /// The square, the sphere folded onto one octahedron face.
    Octahedral,
}

impl ImageProjection {
    /// Reads a document's `projection`, defaulting to the portable one.
    ///
    /// An image that says nothing is latlong, which is what a document written before this field
    /// meant by an image with no shape declared.
    fn read(tag: &str) -> Self {
        match tag {
            "Octahedral" => ImageProjection::Octahedral,
            _ => ImageProjection::Latlong,
        }
    }

    /// The tag this projection is written under.
    fn tag(self) -> &'static str {
        match self {
            ImageProjection::Latlong => "Latlong",
            ImageProjection::Octahedral => "Octahedral",
        }
    }

    /// Whether the loader can read this projection at all.
    fn is_readable(self) -> bool {
        matches!(self, ImageProjection::Latlong)
    }
}

/// Reads an image's projection out of its fields.
fn projection_of(fields: &FieldMap) -> ImageProjection {
    read::field(fields, "projection")
        .and_then(|value| value.variant_tag())
        .map(ImageProjection::read)
        .unwrap_or_default()
}

/// Reads the images an environment light names out of the document's own image list.
///
/// # Why the list is read once and handed down
///
/// The pixels have to reach a file the loader can open, and the document is the only place they
/// exist. Reading them here means `write_world` asks for an image rather than looking for one,
/// and the caller that writes the files is handed the same bytes the emitter referred to rather
/// than re-reading the document and getting a second answer.
fn referenced_images(fields: &FieldMap, lights: &[Light]) -> Vec<SceneImage> {
    let wanted: Vec<&str> = lights
        .iter()
        .filter_map(|light| light.image.as_deref())
        .collect();
    if wanted.is_empty() {
        return Vec::new();
    }
    let mut found = Vec::new();
    for entry in read::list_or_empty(fields, "images", "the scene").unwrap_or_default() {
        let Some(fields) = entry.as_field_map() else {
            continue;
        };
        let Some(label) = read::field(fields, "label").and_then(|value| value.as_str()) else {
            continue;
        };
        if !wanted.contains(&label) {
            continue;
        }
        let size = |name: &str| {
            read::field(fields, name)
                .and_then(|value| read::number(value, name).ok())
                .unwrap_or(0.0)
                .max(0.0) as u32
        };
        let Some(pixels) = read::field(fields, "data").and_then(|value| value.as_bytes()) else {
            continue;
        };
        found.push(SceneImage {
            label: label.to_owned(),
            width: size("width"),
            height: size("height"),
            projection: projection_of(fields),
            pixels: pixels.to_vec(),
        });
    }
    found
}

/// Writes one scene image as a png beside the document.
///
/// # What the bytes are
///
/// Exactly the bytes the document carried. `format` says `rgba8unorm` and the rasterised path
/// uploads the texels as they are and its shaders read them directly; the loader, with no colour
/// management configured, falls back to scene linear too and says so. So writing them unchanged
/// makes both backends read the same numbers, and re-encoding them would put a colour pipeline
/// between two that already agree.
///
/// Eight bits per channel is what the document says and what a png holds, so nothing is lost. A
/// scene whose sky is generated at higher precision than that is quantising it, and a smooth
/// gradient over a large map is where eight bits is first visible.
pub fn write_image(path: &Path, image: &SceneImage) -> EmitResult<()> {
    if image.pixels.len() != (image.width as usize) * (image.height as usize) * 4 {
        return Err(EmitError::Malformed {
            detail: format!(
                "the image '{}' is {} x {} and carries {} bytes, which is not four a texel",
                image.label,
                image.width,
                image.height,
                image.pixels.len()
            ),
        });
    }
    let file = std::fs::File::create(path).map_err(|source| EmitError::Write {
        path: path.to_path_buf(),
        source,
    })?;
    let mut encoder = png::Encoder::new(std::io::BufWriter::new(file), image.width, image.height);
    encoder.set_color(png::ColorType::Rgba);
    encoder.set_depth(png::BitDepth::Eight);
    // Compression is the encoder's own and changes no pixel: a render's sky is written once per
    // render and read once, and the difference between stored and deflated is not the difference
    // between a right image and a wrong one.
    encoder.set_compression(png::Compression::Default);
    let mut writer = encoder.write_header().map_err(|source| EmitError::Write {
        path: path.to_path_buf(),
        source: std::io::Error::other(source),
    })?;
    writer
        .write_image_data(&image.pixels)
        .map_err(|source| EmitError::Write {
            path: path.to_path_buf(),
            source: std::io::Error::other(source),
        })?;
    writer.finish().map_err(|source| EmitError::Write {
        path: path.to_path_buf(),
        source: std::io::Error::other(source),
    })?;
    Ok(())
}

/// Reads which stage each shader belongs to, keyed by the label a material names it by.
///
/// # Invariants
///
/// A shader is a variant, so its stage is its tag and its label is in the payload; reading either
/// the wrong way round produces a map whose every value is nonsense, which is worse than an empty
/// one because it looks answered. A shader that cannot be read is left out rather than defaulted,
/// so a material naming it is reported as naming something the scene does not declare.
fn read_shader_stages(fields: &FieldMap) -> std::collections::HashMap<String, String> {
    let mut stages = std::collections::HashMap::new();
    for shader in read::list_or_empty(fields, "shaders", "the scene").unwrap_or_default() {
        let Some(payload) = shader.variant_fields() else {
            continue;
        };
        let Some(stage) = shader.variant_tag() else {
            continue;
        };
        if let Some(label) = read::field(payload, "label").and_then(|v| v.as_str()) {
            stages.insert(label.to_owned(), stage.to_owned());
        }
    }
    stages
}

/// Writes the materials, honouring the lossy mode.
///
/// # Why a stage is skipped rather than always refused
///
/// The document names the stage a material is drawn in, and only the lighting stage draws a
/// surface Cycles can shade. The other two — shadowing and depthing — exist to feed the
/// rasterised pipeline's own passes, and Cycles derives shadow and depth rays from its own
/// integrator, so there is nothing here for them to become.
///
/// Refusing that unconditionally would make [`LossyMode::Degrade`] useless for every scene in
/// the gallery: every one of them declares a shadowing shader, because every one of them is a
/// lit scene and that is how this workspace writes one. A mode whose whole purpose is to drop
/// what cannot be carried cannot refuse the single most common thing that cannot be carried.
///
/// So the stage is dropped in `Degrade` and recorded, which is a materially different image from
/// the rasterised one rather than a worse rendering of it — and the report is what tells a
/// caller that is what happened.
fn write_materials(
    writer: &mut Writer,
    materials: &[Material],
    stages: &std::collections::HashMap<String, String>,
    mode: LossyMode,
    report: &mut LossyReport,
) -> EmitResult<Vec<String>> {
    // A material names a shader by label; the stage is that shader's. A material whose shader the
    // scene does not declare is treated as not drawable rather than as lighting, because a
    // material with no shader is a broken reference and drawing it with a default closure would
    // put a surface in the frame that nothing asked for.
    let stage_of = |material: &Material| {
        stages
            .get(&material.shader)
            .map(String::as_str)
            .unwrap_or("")
    };
    let drawable = materials
        .iter()
        .filter(|material| is_lighting_stage(stage_of(material)))
        .count();
    if drawable == 0 {
        return match materials.first() {
            Some(material) => Err(EmitError::Unsupported(UnsupportedField::ShaderStage {
                stage: stage_of(material).to_owned(),
            })),
            None => Ok(Vec::new()),
        };
    }

    writer.comment("Materials");
    // The names actually written, so the instance writer can tell a material that exists from one
    // that was dropped. Returning the whole list and letting the caller assume every one of them
    // was written is how a `<state>` ends up naming a shader the document never contained.
    let mut drawn = Vec::with_capacity(drawable);
    for material in materials.iter() {
        if !is_lighting_stage(stage_of(material)) {
            match mode {
                LossyMode::Reject => {
                    return Err(EmitError::Unsupported(UnsupportedField::ShaderStage {
                        stage: stage_of(material).to_owned(),
                    }));
                }
                LossyMode::Degrade => {
                    report.record(UnsupportedField::ShaderStage {
                        stage: stage_of(material).to_owned(),
                    });
                }
            }
            continue;
        }
        material::write_material(writer, material);
        drawn.push(material.label.clone());
    }
    Ok(drawn)
}

/// Whether a shader stage draws a surface Cycles can shade.
///
/// Read off [`crate::standard::Stage`] rather than written out, because the tag is that enum's
/// and a copy of it is a second definition of the same string: it was once written as
/// `LightingShader`, which the enum calls `LightShader`, and every material in the gallery came
/// back as a stage Cycles has no pass for.
fn is_lighting_stage(stage: &str) -> bool {
    stage == crate::standard::Stage::Lighting.tag()
}

/// Writes every instance, each as a transform scope around its mesh.
///
/// The mesh is written inside a `<state>` that names the material, because that is where the
/// loader reads the shader from: `xml_read_mesh` takes `state.shader` and assigns it to the
/// mesh. The scope therefore has to enclose the mesh, and the transform has to enclose both.
fn write_instances(
    writer: &mut Writer,
    instances: &[Instance],
    meshes: &[Mesh],
    materials: &[Material],
    drawn: &[String],
) -> EmitResult<()> {
    if instances.is_empty() {
        return Ok(());
    }
    writer.comment("Instances");
    for instance in instances {
        // An instance naming a mesh or a material that is not in the scene is a broken scene
        // rather than something to skip quietly: the object is simply missing from the frame,
        // and a frame missing an object is a question nobody asked.
        let Some(mesh) = meshes.iter().find(|mesh| mesh.label == instance.mesh) else {
            return Err(EmitError::Malformed {
                detail: format!(
                    "instance '{}' names mesh '{}', which the scene does not declare",
                    instance.label, instance.mesh
                ),
            });
        };
        let Some(material) = materials.iter().find(|by| by.label == instance.material) else {
            return Err(EmitError::Malformed {
                detail: format!(
                    "instance '{}' names material '{}', which the scene does not declare",
                    instance.label, instance.material
                ),
            });
        };
        // A material whose shader was not drawn is not a material any more — its `<shader>` block
        // was never written — and a `<state>` naming it produces `ERROR: Unknown shader`. That is
        // not hypothetical: a scene's shadowing material is dropped in `Degrade` while its
        // instances survive, so the state would name a shader that does not exist.
        //
        // So the instance is skipped along with its material, and the drop is reported rather than
        // left for the renderer to complain about in words nobody reading our output will see.
        if !drawn.contains(&material.label) {
            continue;
        }
        // `<transform>` and `<state>` are both containers, and they nest: the loader handles
        // each of them the same way, copying the read state, applying the attributes to the
        // copy, and recursing into the children with it. The geometry is therefore a child of
        // the state, which is a child of the transform, and writing it as a sibling leaves it
        // outside both scopes.
        //
        // Both wrong nestings fail in the same silent way. A `<state>` written as a leaf puts
        // the mesh outside the scope that names the material, and a `<state>` wrapping nothing
        // leaves nothing in the scene at all. Either way the render succeeds, logs no error,
        // and writes an empty frame — so "no errors in the log" is not evidence that a scene
        // is right. The shape here is the one in the repository's own
        // `examples/scene_cube_surface.xml`, and the recursion is `xml_read_scene` in
        // `src/app/cycles_xml.cpp`.
        if instance_has_transform(&instance.transform) {
            writer.open(
                "transform",
                &transform_attributes(&instance.transform, axes::Rotation::Points),
            );
        }
        writer.open(
            "state",
            // `interpolation="smooth"` is what makes the `N` array above it mean anything. The
            // loader reads it in `xml_read_state` and copies it into `mesh->get_smooth()`
            // (`cycles_xml.cpp:462`), and the default is **flat** — so without this attribute
            // the renderer keeps the array and ignores it, interpolating the face normal
            // across each triangle instead. That is the facet striation this backend was
            // blamed on: raster resolves one value per face, the tracer was resolving within
            // the face from the wrong normals.
            &[
                ("shader", material.label.clone()),
                ("interpolation", "smooth".to_owned()),
            ],
        );
        geometry::write_mesh(writer, mesh);
        writer.close("state");
        if instance_has_transform(&instance.transform) {
            writer.close("transform");
        }
    }
    Ok(())
}

/// Whether a transform is worth writing, which it is not when it is the identity.
fn instance_has_transform(transform: &Transform) -> bool {
    transform.translation != [0.0; 3]
        || transform.rotation != [0.0; 3]
        || transform.scale != [1.0; 3]
}

/// The attributes for one transform, as the loader reads them.
///
/// `kind` is which of the two things a rotation is a rotation **of**, and it is a parameter
/// rather than an inference because the two are written by the same function and disagree:
/// see [`axes::Rotation`].
fn transform_attributes(
    transform: &Transform,
    kind: axes::Rotation,
) -> Vec<(&'static str, String)> {
    let mut attributes = Vec::with_capacity(3);
    if transform.translation != [0.0; 3] {
        let translation = axes::position(transform.translation);
        attributes.push((
            "translate",
            Writer::color(translation[0], translation[1], translation[2]),
        ));
    }
    if let Some((axis, angle)) = transform::axis_angle(transform.rotation, kind) {
        attributes.push((
            "rotate",
            format!("{}, {}, {}, {}", angle, axis[0], axis[1], axis[2]),
        ));
    }
    if transform.scale != [1.0; 3] {
        let scale = axes::scale(transform.scale);
        attributes.push(("scale", Writer::color(scale[0], scale[1], scale[2])));
    }
    attributes
}
