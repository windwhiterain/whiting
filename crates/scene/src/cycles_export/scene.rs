//! Assembling the document.
//!
//! The order of the blocks is fixed by the loader rather than by taste: the film and the
//! integrator are read wherever they appear, the camera takes the transform scope it is
//! written in, and every mesh and light takes the scope around it. Writing them in a
//! readable order therefore costs nothing and makes the file something a person can follow
//! when a scene does not look right.

use super::error::{EmitError, EmitResult, UnsupportedField};
use super::geometry::{self, Mesh};
use super::light::{self, Light};
use super::lossy::LossyReport;
use super::material::{self, Material};
use super::read;
use super::settings;
use super::transform::{self, Transform};
use super::writer::Writer;
use super::{EmitOptions, LossyMode};
use definition::{FieldMap, Value};

/// Writes a whole scene document.
pub fn write(scene: &Value, options: &EmitOptions, report: &mut LossyReport) -> EmitResult<String> {
    let fields = scene.as_field_map().ok_or_else(|| EmitError::Malformed {
        detail: "the scene is not a structure".to_owned(),
    })?;

    // Everything is read before anything is written, so a scene refused in `Reject` leaves no
    // half-written document for someone to find and try to debug.
    let meshes = geometry::read_meshes(
        read::list_or_empty(fields, "meshes", "the scene")?,
        options.lossy,
        report,
    )?;
    let materials = material::read_materials(
        read::list_or_empty(fields, "mesh_materials", "the scene")?,
        options.lossy,
        report,
    )?;
    let lights = read_lights(
        read::list_or_empty(fields, "lights", "the scene")?,
        options.lossy,
        report,
    )?;
    let instances = read_instances(fields)?;
    let camera = read_camera(fields)?;

    let mut writer = Writer::new();

    writer.comment("Generated by whiting. Do not edit; re-emit from the scene document.");
    settings::write_film(&mut writer, options);
    settings::write_integrator(&mut writer, options);
    write_camera(&mut writer, &camera);
    write_world(&mut writer, &lights);
    write_materials(&mut writer, &materials)?;
    write_lights(&mut writer, &lights);
    write_instances(&mut writer, &instances, &meshes, &materials)?;

    Ok(writer.finish())
}

/// Reads every light, honouring the lossy mode.
///
/// A light with no `light_type` mapping is refused in [`LossyMode::Reject`] and recorded in
/// [`LossyMode::Degrade`]. In the degrading case the frame still renders, with that light
/// simply not in it, which is a materially different image rather than a marginally worse
/// one — so the report is the only thing standing between an author and a scene that
/// renders without the light they wrote.
fn read_lights(
    lights: &[Value],
    mode: LossyMode,
    report: &mut LossyReport,
) -> EmitResult<Vec<Light>> {
    let mut out = Vec::with_capacity(lights.len());
    for value in lights {
        match light::read_light(value) {
            Ok(light) => out.push(light),
            Err(EmitError::Unsupported(UnsupportedField::Light { kind })) => {
                light::reject_or_record(&kind, mode, report)?;
            }
            Err(error) => return Err(error),
        }
    }
    Ok(out)
}

/// Writes every punctual light.
///
/// The environment light is skipped here because [`write_world`] has already written it into
/// the `<background>` element, and the loader has one world and no second place to put
/// another.
///
/// A light is written inside its own transform scope rather than the world's, so that its
/// position and orientation compose the way an instance's do. A directional light has no
/// position, so it takes only a rotation, and the negative Z of that rotation is the way the
/// light travels — which was confirmed by rendering a sun with no rotation, where it lit
/// faces pointing along its own axis.
fn write_lights(writer: &mut Writer, lights: &[Light]) {
    let punctual: Vec<&Light> = lights
        .iter()
        .filter(|light| light.kind != "background")
        .collect();
    if punctual.is_empty() {
        return;
    }
    writer.comment("Lights");
    for light in punctual {
        light::write_light(writer, light);
    }
}

fn list<'a>(fields: &'a FieldMap, name: &str) -> EmitResult<&'a [Value]> {
    read::list_or_empty(fields, name, "the scene")
}

/// One instance: which mesh, where, drawn by which material.
struct Instance {
    label: String,
    mesh: String,
    material: String,
    transform: Transform,
}

fn read_instances(fields: &FieldMap) -> EmitResult<Vec<Instance>> {
    let mut out = Vec::new();
    for entry in list(fields, "instances")? {
        let instance_fields = entry.as_field_map().ok_or_else(|| EmitError::Malformed {
            detail: "an instance is not a structure".to_owned(),
        })?;
        let label = read::text_field(instance_fields, "label", "an instance")?;
        out.push(Instance {
            mesh: read::text_field(instance_fields, "mesh", &format!("instance '{label}'"))?,
            material: read::text_field(
                instance_fields,
                "material",
                &format!("instance '{label}'"),
            )?,
            transform: transform::read_transform(
                read::field(instance_fields, "transform"),
                &format!("instance '{label}'"),
            )?,
            label,
        });
    }
    Ok(out)
}

/// The camera: where it stands, which way it looks, and what it can see.
struct Camera {
    transform: Transform,
    field_of_view: f64,
    width: usize,
    height: usize,
}

fn read_camera(fields: &FieldMap) -> EmitResult<Camera> {
    let cameras = list(fields, "cameras")?;
    let Some(first) = cameras.first() else {
        return Ok(Camera {
            transform: Transform::identity(),
            field_of_view: std::f64::consts::FRAC_PI_2,
            width: 1920,
            height: 1080,
        });
    };
    let camera_fields = first.as_field_map().ok_or_else(|| EmitError::Malformed {
        detail: "a camera is not a structure".to_owned(),
    })?;
    Ok(Camera {
        transform: transform::read_transform(
            read::field(camera_fields, "transform"),
            "the camera",
        )?,
        field_of_view: read::field(camera_fields, "field_of_view")
            .and_then(|value| read::number(value, "field_of_view").ok())
            .unwrap_or(std::f64::consts::FRAC_PI_2),
        width: read::field(camera_fields, "width")
            .and_then(|value| read::number(value, "width").ok())
            .unwrap_or(1920.0) as usize,
        height: read::field(camera_fields, "height")
            .and_then(|value| read::number(value, "height").ok())
            .unwrap_or(1080.0) as usize,
    })
}

/// Writes the camera inside its transform scope.
///
/// The `width` and `height` on the camera element are the render's dimensions, and the
/// loader overrides them from the command line when those are given, so writing them here
/// makes the file self-contained and a bare `cycles scene.xml` still produces a frame.
fn write_camera(writer: &mut Writer, camera: &Camera) {
    writer.comment("Camera");
    // The loader reads `width`, `height` and the camera's own sockets from the `<camera>`
    // element, and takes the transform from the enclosing scope, so the camera is a sibling
    // of the transform rather than a child of it. `xml_read_camera` calls `cam->set_matrix`
    // with `state.tfm` and never looks at the element's own transform attributes.
    writer.open("transform", &transform_attributes(&camera.transform));
    writer.leaf(
        "camera",
        &[
            ("width", camera.width.to_string()),
            ("height", camera.height.to_string()),
            ("type", "perspective".to_owned()),
            ("fov", camera.field_of_view.to_string()),
        ],
    );
    writer.close("transform");
}

/// Writes the world.
///
/// Only one environment light is written, and only when the scene has one. Cycles takes the
/// world from a single `<background>` element, so a second environment light would have
/// nowhere to go; the scene document already refuses a second one.
fn write_world(writer: &mut Writer, lights: &[Light]) {
    let Some(environment) = lights.iter().find(|light| light.kind == "background") else {
        return;
    };
    writer.comment("World");
    writer.open_bare("background");
    match &environment.image {
        Some(image) => {
            writer.leaf(
                "environment_texture",
                &[
                    ("name", "world_texture".to_owned()),
                    ("filename", image.clone()),
                ],
            );
            writer.leaf(
                "background",
                &[
                    ("name", "world".to_owned()),
                    ("strength", environment.strength.to_string()),
                ],
            );
            writer.leaf(
                "connect",
                &[
                    ("from", "world_texture color".to_owned()),
                    ("to", "world color".to_owned()),
                ],
            );
            writer.leaf(
                "connect",
                &[
                    ("from", "world background".to_owned()),
                    ("to", "output surface".to_owned()),
                ],
            );
        }
        None => {
            writer.leaf(
                "background",
                &[
                    ("name", "world".to_owned()),
                    (
                        "color",
                        Writer::color(
                            environment.color[0],
                            environment.color[1],
                            environment.color[2],
                        ),
                    ),
                    ("strength", environment.strength.to_string()),
                ],
            );
            writer.leaf(
                "connect",
                &[
                    ("from", "world background".to_owned()),
                    ("to", "output surface".to_owned()),
                ],
            );
        }
    }
    writer.close("background");
}

fn write_materials(writer: &mut Writer, materials: &[Material]) -> EmitResult<()> {
    if materials.is_empty() {
        return Ok(());
    }
    writer.comment("Materials");
    for material in materials {
        if material.shader != STAGE_LIGHTING {
            // The document names the stage a material is drawn in, and only the lighting
            // stage draws a surface Cycles can shade. The other two exist to feed the
            // rasterised pipeline's own passes, which have no equivalent here because
            // Cycles derives shadow and depth rays from its integrator.
            return Err(EmitError::Unsupported(UnsupportedField::ShaderStage {
                stage: material.shader.clone(),
            }));
        }
        material::write_material(writer, material);
    }
    Ok(())
}

/// The shader stage that draws a lit surface.
const STAGE_LIGHTING: &str = "LightingShader";

/// Writes every instance, each as a transform scope around its mesh.
///
/// The mesh is written inside a `<state>` that names the material, because that is where the
/// loader reads the shader from: `xml_read_mesh` takes `state.shader` and assigns it to the
/// mesh. The scope therefore has to enclose the mesh, and the transform has to enclose both.
fn write_instances(
    writer: &mut Writer,
    instances: &[Instance],
    meshes: &[Mesh],
    materials: &[Material],
) -> EmitResult<()> {
    if instances.is_empty() {
        return Ok(());
    }
    writer.comment("Instances");
    for instance in instances {
        // An instance naming a mesh or a material that is not in the scene is a broken scene
        // rather than something to skip quietly: the object is simply missing from the frame,
        // and a frame missing an object is a question nobody asked.
        let Some(mesh) = meshes.iter().find(|mesh| mesh.label == instance.mesh) else {
            return Err(EmitError::Malformed {
                detail: format!(
                    "instance '{}' names mesh '{}', which the scene does not declare",
                    instance.label, instance.mesh
                ),
            });
        };
        let Some(material) = materials.iter().find(|by| by.label == instance.material) else {
            return Err(EmitError::Malformed {
                detail: format!(
                    "instance '{}' names material '{}', which the scene does not declare",
                    instance.label, instance.material
                ),
            });
        };
        // `<transform>` and `<state>` are both containers, and they nest: the loader handles
        // each of them the same way, copying the read state, applying the attributes to the
        // copy, and recursing into the children with it. The geometry is therefore a child of
        // the state, which is a child of the transform, and writing it as a sibling leaves it
        // outside both scopes.
        //
        // Both wrong nestings fail in the same silent way. A `<state>` written as a leaf puts
        // the mesh outside the scope that names the material, and a `<state>` wrapping nothing
        // leaves nothing in the scene at all. Either way the render succeeds, logs no error,
        // and writes an empty frame — so "no errors in the log" is not evidence that a scene
        // is right. The shape here is the one in the repository's own
        // `examples/scene_cube_surface.xml`, and the recursion is `xml_read_scene` in
        // `src/app/cycles_xml.cpp`.
        if instance_has_transform(&instance.transform) {
            writer.open("transform", &transform_attributes(&instance.transform));
        }
        writer.open("state", &[("shader", material.label.clone())]);
        geometry::write_mesh(writer, mesh);
        writer.close("state");
        if instance_has_transform(&instance.transform) {
            writer.close("transform");
        }
    }
    Ok(())
}

/// Whether a transform is worth writing, which it is not when it is the identity.
fn instance_has_transform(transform: &Transform) -> bool {
    transform.translation != [0.0; 3]
        || transform.rotation != [0.0; 3]
        || transform.scale != [1.0; 3]
}

/// The attributes for one transform, as the loader reads them.
fn transform_attributes(transform: &Transform) -> Vec<(&'static str, String)> {
    let mut attributes = Vec::with_capacity(3);
    if transform.translation != [0.0; 3] {
        attributes.push((
            "translate",
            Writer::color(
                transform.translation[0],
                transform.translation[1],
                transform.translation[2],
            ),
        ));
    }
    if let Some((axis, angle)) = transform::axis_angle(transform.rotation) {
        attributes.push((
            "rotate",
            format!("{}, {}, {}, {}", angle, axis[0], axis[1], axis[2]),
        ));
    }
    if transform.scale != [1.0; 3] {
        attributes.push((
            "scale",
            Writer::color(transform.scale[0], transform.scale[1], transform.scale[2]),
        ));
    }
    attributes
}
